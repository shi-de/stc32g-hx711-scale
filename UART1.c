static void Scale_PutLong(u8 *bytes, long value)
{
    u32 raw;
    raw = (u32)value;
    bytes[0] = (u8)(raw >> 24);
    bytes[1] = (u8)(raw >> 16);
    bytes[2] = (u8)(raw >> 8);
    bytes[3] = (u8)raw;
}

static long Scale_GetLong(const u8 *bytes)
{
    u32 raw;
    raw = ((u32)bytes[0] << 24) | ((u32)bytes[1] << 16) |
          ((u32)bytes[2] << 8) | (u32)bytes[3];
    return (long)raw;
}

static void Scale_IapDisable(void)
{
    IAP_CONTR = 0;
    IAP_CMD = 0;
    IAP_TRIG = 0;
    IAP_ADDRE = 0xff;
    IAP_ADDRH = 0xff;
    IAP_ADDRL = 0xff;
}

static void Scale_IapTrigger(void)
{
    bit old_ea;
    old_ea = EA;
    EA = 0;
    IAP_TRIG = 0x5a;
    IAP_TRIG = 0xa5;
    _nop_(); _nop_(); _nop_(); _nop_();
    EA = old_ea;
}

static void Scale_IapAddress(u32 address)
{
    IAP_ADDRE = (u8)(address >> 16);
    IAP_ADDRH = (u8)(address >> 8);
    IAP_ADDRL = (u8)address;
}

static void Scale_IapErase(u32 address)
{
    IAP_CONTR = 0x80;
    IAP_TPS = (u8)(MAIN_Fosc / 1000000L);
    IAP_CMD = 3;
    Scale_IapAddress(address);
    Scale_IapTrigger();
    Scale_IapDisable();
}

static u8 Scale_IapReadByte(u32 address)
{
    u8 value;
    IAP_CONTR = 0x80;
    IAP_TPS = (u8)(MAIN_Fosc / 1000000L);
    IAP_CMD = 1;
    Scale_IapAddress(address);
    Scale_IapTrigger();
    value = IAP_DATA;
    Scale_IapDisable();
    return value;
}

static void Scale_IapWriteByte(u32 address, u8 value)
{
    IAP_CONTR = 0x80;
    IAP_TPS = (u8)(MAIN_Fosc / 1000000L);
    IAP_CMD = 2;
    Scale_IapAddress(address);
    IAP_DATA = value;
    Scale_IapTrigger();
    Scale_IapDisable();
}

void Scale_LoadConfig(void)
{
    u8 bytes[SCALE_CONFIG_SIZE];
    u8 i;
    u8 checksum;
    unsigned char ok;
    long raw;

    for (i = 0; i < SCALE_CONFIG_SIZE; i++) bytes[i] = Scale_IapReadByte(SCALE_EEPROM_ADDR + i);
    checksum = 0;
    for (i = 0; i < SCALE_CONFIG_SIZE - 1; i++) checksum ^= bytes[i];

    scaleState.zero_raw = 0;
    scaleState.scale_counts_per_gram = 0;
    scaleState.known_mass_grams = 500;
    scaleState.unit_kg = 0;
    scaleState.peak_hold = 0;
    scaleState.peak_grams = 0;
    scaleState.display_grams = 0;
    scaleState.last_raw = 0;
    scaleState.stable = 0;
    scaleState.sensor_ok = 0;
    scaleState.using_default = 0;
    scaleState.has_sample = 0;

    if (bytes[0] == SCALE_CONFIG_MAGIC && bytes[1] == SCALE_CONFIG_VERSION &&
        checksum == bytes[SCALE_CONFIG_SIZE - 1])
    {
        scaleState.zero_raw = Scale_GetLong(&bytes[2]);
        scaleState.scale_counts_per_gram = Scale_GetLong(&bytes[6]);
        scaleState.known_mass_grams = (unsigned int)(((u16)bytes[10] << 8) | bytes[11]);
        scaleState.unit_kg = bytes[12] ? 1 : 0;
        scaleState.peak_hold = bytes[13] ? 1 : 0;
        scaleState.using_default = bytes[14] ? 1 : 0;
    }
    if (scaleState.scale_counts_per_gram == 0)
    {
        raw = HX711_ReadAverage(8, &ok);
        if (ok)
        {
            scaleState.zero_raw = raw;
            scaleState.scale_counts_per_gram = SCALE_DEFAULT_COUNTS_PER_GRAM;
            scaleState.sensor_ok = 1;
            scaleState.using_default = 1;
            Scale_SaveConfig();
        }
    }
    if (scaleState.scale_counts_per_gram != 0 && scaleState.using_default)
    {
        raw = HX711_ReadAverage(8, &ok);
        if (ok)
        {
            scaleState.zero_raw = raw;
            scaleState.sensor_ok = 1;
        }
    }
}

void Scale_SaveConfig(void)
{
    u8 bytes[SCALE_CONFIG_SIZE];
    u8 i;
    u8 checksum;

    bytes[0] = SCALE_CONFIG_MAGIC;
    bytes[1] = SCALE_CONFIG_VERSION;
    Scale_PutLong(&bytes[2], scaleState.zero_raw);
    Scale_PutLong(&bytes[6], scaleState.scale_counts_per_gram);
    bytes[10] = (u8)(scaleState.known_mass_grams >> 8);
    bytes[11] = (u8)scaleState.known_mass_grams;
    bytes[12] = scaleState.unit_kg;
    bytes[13] = scaleState.peak_hold;
    bytes[14] = scaleState.using_default;
    checksum = 0;
    for (i = 0; i < SCALE_CONFIG_SIZE - 1; i++) checksum ^= bytes[i];
    bytes[15] = checksum;

    Scale_IapErase(SCALE_EEPROM_ADDR);
    for (i = 0; i < SCALE_CONFIG_SIZE; i++) Scale_IapWriteByte(SCALE_EEPROM_ADDR + i, bytes[i]);
}

void Scale_Tare(void)
{
    unsigned char ok;
    long raw;
    raw = HX711_ReadAverage(8, &ok);
    if (ok)
    {
        scaleState.zero_raw = raw;
        scaleState.display_grams = 0;
        scaleState.peak_grams = 0;
        scaleState.has_sample = 0;
        scaleState.sensor_ok = 1;
        if (scaleState.scale_counts_per_gram == 0)
        {
            scaleState.scale_counts_per_gram = SCALE_DEFAULT_COUNTS_PER_GRAM;
            scaleState.using_default = 1;
        }
        Scale_SaveConfig();
    }
}

unsigned char Scale_Calibrate(unsigned int known_mass_grams)
{
    unsigned char ok;
    long raw;
    long scale;
    if (known_mass_grams == 0) return 0;
    raw = HX711_ReadAverage(8, &ok);
    if (!ok) return 0;
    scale = ScaleMath_CalculateScale(scaleState.zero_raw, raw, known_mass_grams);
    if (scale == 0) return 0;
    scaleState.scale_counts_per_gram = scale;
    scaleState.known_mass_grams = known_mass_grams;
    scaleState.display_grams = 0;
    scaleState.peak_grams = 0;
    scaleState.has_sample = 0;
    scaleState.sensor_ok = 1;
    scaleState.using_default = 0;
    Scale_SaveConfig();
    return 1;
}

static void Scale_ProcessSample(void)
{
    unsigned char ok;
    long raw;
    raw = HX711_ReadAverage(5, &ok);
    if (!ok)
    {
        scaleState.sensor_ok = 0;
        return;
    }
    scaleState.sensor_ok = 1;
    if (scaleState.has_sample) scaleState.stable = ScaleMath_IsStable(scaleState.last_raw, raw, SCALE_STABLE_THRESHOLD);
    else { scaleState.stable = 0; scaleState.has_sample = 1; }
    scaleState.last_raw = raw;
    if (scaleState.scale_counts_per_gram != 0) scaleState.display_grams = ScaleMath_WeightGrams(raw, scaleState.zero_raw, scaleState.scale_counts_per_gram);
    else scaleState.display_grams = 0;
    if (scaleState.peak_hold && scaleState.display_grams > scaleState.peak_grams) scaleState.peak_grams = scaleState.display_grams;
}

