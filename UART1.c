void KeyScan(void)
{
    u8 rawKey;

    KeyValue = KEY_NULL;
    KeyRepeat = 0;
    KeyScanRaw();
    rawKey = KeyValue;
    KeyValue = KEY_NULL;

    if (rawKey >= 16)
    {
        if (KeyReported)
        {
            if (KeyDebounceCount < KEY_DEBOUNCE_SAMPLES)
                KeyDebounceCount++;
            if (KeyDebounceCount >= KEY_DEBOUNCE_SAMPLES)
            {
                KeyCandidateValue = KEY_NULL;
                KeyDebounceCount = 0;
                KeyHoldCount = 0;
                KeyRepeatCount = 0;
                KeyReported = 0;
            }
        }
        else
        {
            KeyCandidateValue = KEY_NULL;
            KeyDebounceCount = 0;
            KeyHoldCount = 0;
            KeyRepeatCount = 0;
        }
        return;
    }

    if (!KeyReported)
    {
        KeyCandidateValue = rawKey;
        KeyDebounceCount = 0;
        KeyHoldCount = 0;
        KeyRepeatCount = 0;
        KeyReported = 1;
        KeyValue = rawKey;
    }
    else if (rawKey == KeyCandidateValue)
    {
        if (KeyHoldCount < 255) KeyHoldCount++;
        if (KeyHoldCount >= KEY_HOLD_START_SAMPLES)
        {
            if (KeyRepeatCount + 1 >= KEY_REPEAT_INTERVAL_SAMPLES)
            {
                KeyRepeatCount = 0;
                KeyValue = rawKey;
                KeyRepeat = 1;
            }
            else
            {
                KeyRepeatCount++;
            }
        }
    }
}
